def _find_all(patterns, text):
    out = []
    for p in patterns:
        out += [m.group(0).lower() for m in re.finditer(p, text, flags=re.I)]
    return out

def check_ad(text, max_words=MAX_WORDS):
    t = (text or "").strip()
    n = len(re.findall(r"[A-Za-z0-9'\u2019-]+", t))
    interp, value = _find_all(INTERPRETIVE_PATTERNS, t), _find_all(VALUE_JUDGMENT_PATTERNS, t)
    comps, wesee = _find_all(COMPARISON_PATTERNS, t), _find_all(WE_SEE_PATTERNS, t)
    rep = {
        "words": n, "interpretive": interp, "value_judgment": value,
        "over_length": n > max_words, "empty": n == 0,
        "has_color": any(re.search(rf"\b{c}\b", t, flags=re.I) for c in COLOR_WORDS),
        "has_spatial": len({w for w in SPATIAL_WORDS if re.search(rf"\b{re.escape(w)}", t, flags=re.I)}) >= 2,
        "comparisons": comps, "has_comparison": len(comps) > 0,
        "we_see": wesee,
        "preamble": bool(re.search(PREAMBLE_PATTERN, t, flags=re.I)),
        "is_are": len(re.findall(r"\b(?:is|are)\b", t, flags=re.I)),
        "was_were": len(re.findall(r"\b(?:was|were)\b", t, flags=re.I)),
    }
    rep["hard_violations"] = len(interp) + len(value) + int(rep["over_length"]) + int(rep["empty"])
    rep["compliant_hard"] = rep["hard_violations"] == 0
    return rep

def summarize_conditions(texts_by_cond, seconds_by_cond=None):
    """texts_by_cond: {cond: [texts]}. Table of mean metrics by condition."""
    rows = []
    for c, texts in texts_by_cond.items():
        reps = [check_ad(t) for t in texts]
        nw = sum(r["words"] for r in reps) or 1
        row = {
            "condition": c,
            "n": len(reps),
            "words (mean)": np.mean([r["words"] for r in reps]),
            "% compliant (hard rules)": 100 * np.mean([r["compliant_hard"] for r in reps]),
            "interpretive terms /100 words": 100 * sum(len(r["interpretive"]) for r in reps) / nw,
            "value judgments /100 words": 100 * sum(len(r["value_judgment"]) for r in reps) / nw,
            "% over length limit": 100 * np.mean([r["over_length"] for r in reps]),
            "% with colours": 100 * np.mean([r["has_color"] for r in reps]),
            "% with spatial references": 100 * np.mean([r["has_spatial"] for r in reps]),
            "% with comparisons": 100 * np.mean([r["has_comparison"] for r in reps]),
            "'we see' etc. /100 words": 100 * sum(len(r["we_see"]) for r in reps) / nw,
            "% with preamble": 100 * np.mean([r["preamble"] for r in reps]),
            "was/were /100 words": 100 * sum(r["was_were"] for r in reps) / nw,
        }
        if seconds_by_cond and c in seconds_by_cond:
            row["seconds per AD (mean)"] = np.mean(seconds_by_cond[c])
        rows.append(row)
    return pd.DataFrame(rows).set_index("condition").round(1)

