    done_path = f"{OUT}/annotation_sheet_completed.csv"
    if path is None:
        from google.colab import files
        print("Upload the completed CSV:")
        up = files.upload()
        assert up, "No file uploaded."
        open(done_path, "wb").write(up[next(iter(up))])
    elif os.path.abspath(path) != os.path.abspath(done_path):
        shutil.copy(path, done_path)
    key = json.load(open(key_path)); codes = list(CODES)
    d = pd.read_csv(done_path)
    missing_cols = [c for c in ["text_tag", "sentence"] + codes if c not in d.columns]
    assert not missing_cols, f"The file is missing these columns: {missing_cols} (do not rename them)."
    d[codes] = d[codes].apply(pd.to_numeric, errors="coerce")
    empty = int(d[codes].isna().sum().sum())
    if empty:
        print(f"WARNING: {empty} code cells are empty or non-numeric (they will be ignored). Enter 0 where the answer is 'no'.")
    d["cond"] = d["text_tag"].map(lambda t: key[t]["cond"])
    d["words"] = d["sentence"].map(lambda s: len(re.findall(r"[A-Za-z0-9'-]+", str(s))))
    g = d.groupby("cond")
    tab = g[codes].sum().astype(int)
    tab["sentences"] = g.size(); tab["words"] = g["words"].sum()
    per100 = (g[codes].sum().div(g["words"].sum(), axis=0) * 100).round(2).add_suffix(" /100 words")
    share = (g[codes].sum().div(g.size(), axis=0) * 100).round(1).add_suffix(" % sentences")
    print("=== COUNTS BY CONDITION ==="); display(tab)
    print("\n=== PER 100 WORDS ==="); display(per100)
    print("\n=== % OF SENTENCES WITH THE CODE ==="); display(share)
    per_img = d.groupby(["image", "cond"])[codes].sum().astype(int)
    print("\n=== BY IMAGE ==="); display(per_img)

    d["auto_interpretive"] = d["sentence"].map(lambda s: int(len(check_ad(str(s))["interpretive"]) > 0))
    d["auto_evaluative"] = d["sentence"].map(lambda s: int(len(check_ad(str(s))["value_judgment"]) > 0))
    def kappa(x, y):
        x, y = np.array(x), np.array(y); po = (x == y).mean()
        pe = sum(((x == v).mean() * (y == v).mean()) for v in (0, 1))
        return (po - pe) / (1 - pe) if pe < 1 else float("nan")
    print("\n=== AUTOMATIC CHECKER vs MANUAL ANNOTATION ===")
    for a_, m_ in (("auto_interpretive", "interpretive"), ("auto_evaluative", "evaluative")):
        ok = d[m_].notna()
        x, y = d.loc[ok, a_], d.loc[ok, m_].astype(int)
        fp = int(((x == 1) & (y == 0)).sum()); fn = int(((x == 0) & (y == 1)).sum())
        print(f"{m_:13s} agreement {(x == y).mean()*100:.0f}% | kappa {kappa(x, y):.2f} | false positives {fp} | false negatives {fn} (n={len(x)})")
    if d.groupby("cond").size().min() > 0 and len(d["cond"].unique()) == 2:
        from scipy.stats import fisher_exact
        a, b = sorted(d["cond"].unique())
        print("\n=== Fisher exact test on sentences (exploratory; sentences from the same image are not independent) ===")
        for code in ["interpretive", "evaluative", "spatial", "colour", "comparison", "error"]:
            x = d[d.cond == a][code].dropna(); y = d[d.cond == b][code].dropna()
            odds, p = fisher_exact([[int(x.sum()), int(len(x) - x.sum())], [int(y.sum()), int(len(y) - y.sum())]])
            print(f"{code:13s} {a}: {int(x.sum())}/{len(x)} | {b}: {int(y.sum())}/{len(y)} | p={p:.3f}")

    G = d.groupby("cond"); words = G["words"].sum(); sums = G[codes].sum()
    table2 = pd.DataFrame({"Code": codes})
    for cond, lab in (("A_zero_shot", "A"), ("B_snyder_prompt", "B")):
        table2[f"{lab}: sentences"] = sums.loc[cond].values.astype(int)
        table2[f"{lab}: per 100 words"] = (sums.loc[cond].values / words[cond] * 100).round(1)
    tot = {"Code": "Total (sentences | words)"}
    for cond, lab in (("A_zero_shot", "A"), ("B_snyder_prompt", "B")):
        tot[f"{lab}: sentences"] = int((d.cond == cond).sum()); tot[f"{lab}: per 100 words"] = int(words[cond])
    table2 = pd.concat([table2, pd.DataFrame([tot])], ignore_index=True)
    print("\n=== PAPER TABLE 2 (last row: total sentences | total words) ===")
    display(table2)
    table2.to_csv(f"{OUT}/table2.csv", index=False)
    d.to_csv(f"{OUT}/annotation_analysis_by_sentence.csv", index=False)
    print("\nSaved in", OUT, ": annotation_sheet_completed.csv, table2.csv, annotation_analysis_by_sentence.csv (they will be included in the ZIP).")
    return d, tab, table2

