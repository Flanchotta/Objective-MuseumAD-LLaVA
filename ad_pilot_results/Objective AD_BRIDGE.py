        "USER: <image>\n"
        "You are a professional audio describer in an art museum. Write an audio description of this artwork "
        "for a blind or low-vision visitor who will HEAR it, not read it. Follow these rules of objective audio description.\n\n"
        "RULES\n"
        "1. What you see is what you say. Describe only what is visible. Do not interpret: no emotions, mood, atmosphere, "
