def _get(url, params=None, tries=4, verbose=False):
    last = None
    for k in range(tries):
        try:
            r = requests.get(url, params=params, timeout=30, headers=HEADERS)
            if r.status_code == 200:
                return r
            last = f"HTTP {r.status_code}"
        except requests.RequestException as e:
            last = repr(e)
        time.sleep(1.5 * (k + 1))
    if verbose:
        print("  Request error:", url, "->", last)
    return None

def from_aic(n):
    rows, seen = [], set()
    for page in range(1, 11):
        params = {"q": "painting", "query[term][is_public_domain]": "true", "limit": 100, "page": page,
                  "fields": "id,title,artist_title,date_display,image_id,classification_title,style_title,"
                            "place_of_origin,is_public_domain"}
        r = _get(f"{AIC}/artworks/search", params, verbose=(page == 1))
        if r is None:
            break
        data = r.json().get("data", [])
        if not data:
            break
        for x in data:
            if x["id"] in seen or not x.get("image_id") or not x.get("is_public_domain"):
                continue
            seen.add(x["id"])
            cl = (x.get("classification_title") or "").lower()
            if CLASS_FILTER is None or any(c in cl for c in CLASS_FILTER):
                rows.append(x)
    print(f"  AIC: {len(rows)} candidate artworks (public domain, with images, filter: {CLASS_FILTER})")
    random.Random(SEED).shuffle(rows)
    chosen, ids = [], set()
    artists, titles, styles = set(), set(), set()
    for strict in (True, False):
        for x in rows:
            if len(chosen) >= n:
                break
            if x["id"] in ids:
                continue
            a = (x.get("artist_title") or "unknown").strip().lower()
            t = (x.get("title") or "").strip().lower()
            st = (x.get("style_title") or "").strip().lower()
            if a in artists or t in titles:
                continue
            if strict and st and st in styles:
                continue
            resp = _get(f"https://www.artic.edu/iiif/2/{x['image_id']}/full/843,/0/default.jpg")
            try:
                img = Image.open(BytesIO(resp.content)).convert("RGB") if resp is not None else None
            except Exception:
                img = None
            if img is None:
                continue
            ids.add(x["id"]); artists.add(a); titles.add(t)
            if st: styles.add(st)
            chosen.append((img, {"file": f"aic_{x['id']}.jpg", "source": "Art Institute of Chicago Open Access",
                                 "licence": "Public domain / CC0 (AIC Open Access)", "object_id": x["id"],
                                 "title": x.get("title"), "artist": x.get("artist_title") or "unknown",
                                 "date": x.get("date_display"), "style": x.get("style_title"),
                                 "url": f"https://www.artic.edu/artworks/{x['id']}"}))
    return chosen

