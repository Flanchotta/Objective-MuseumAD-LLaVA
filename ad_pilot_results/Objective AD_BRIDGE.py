        "Describe the visible signs instead of the feeling: 'her head is bowed and her eyes are closed', not 'she is sad'.\n"
        "2. Go from the general to the specific. First the whole picture: subject, setting, how many figures. "
        "Then the main elements. Then smaller details.\n"
        "3. Be selective. You cannot say everything. Say first what matters most for understanding the artwork; "
